DROP SCHEMA IF EXISTS oficina CASCADE;
CREATE SCHEMA oficina;
SET search_path TO oficina;

-- --------------------------------------------------------------------------
-- 1. CLIENTE
-- Mapeamento: entidade regular -> tabela.
-- O atributo composto "Endereço" foi decomposto em logradouro, cidade, UF e CEP.
-- Extensão: cliente PF ou PJ (frotas de empresas também usam a oficina).
-- --------------------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente      INT GENERATED BY DEFAULT AS IDENTITY,
    tipo_cliente    CHAR(2)      NOT NULL,
    nome            VARCHAR(100) NOT NULL,  -- nome completo (PF) ou razão social (PJ)
    cpf             CHAR(11),
    cnpj            CHAR(14),
    telefone        VARCHAR(15)  NOT NULL,
    email           VARCHAR(100),
    logradouro      VARCHAR(150) NOT NULL,
    cidade          VARCHAR(60)  NOT NULL,
    uf              CHAR(2)      NOT NULL,
    cep             CHAR(8)      NOT NULL,
    data_cadastro   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cliente           PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_cpf       UNIQUE (cpf),
    CONSTRAINT uq_cliente_cnpj      UNIQUE (cnpj),
    CONSTRAINT uq_cliente_email     UNIQUE (email),
    CONSTRAINT ck_cliente_tipo      CHECK (tipo_cliente IN ('PF', 'PJ')),
    CONSTRAINT ck_cliente_documento CHECK (
        (tipo_cliente = 'PF' AND cpf  IS NOT NULL AND cnpj IS NULL) OR
        (tipo_cliente = 'PJ' AND cnpj IS NOT NULL AND cpf  IS NULL)
    )
);

-- --------------------------------------------------------------------------
-- 2. VEICULO
-- Mapeamento: relacionamento 1:N (Cliente possui Veículos) -> FK no lado N.
-- Correção do modelo conceitual: o vínculo fixo Veículo -> Equipe foi
-- removido. A equipe muda a cada visita, por isso fica na Ordem de Serviço.
-- --------------------------------------------------------------------------
CREATE TABLE veiculo (
    id_veiculo  INT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente  INT         NOT NULL,
    placa       CHAR(7)     NOT NULL,
    marca       VARCHAR(30) NOT NULL,
    modelo      VARCHAR(50) NOT NULL,
    ano         SMALLINT    NOT NULL,
    CONSTRAINT pk_veiculo PRIMARY KEY (id_veiculo),
    CONSTRAINT uq_veiculo_placa UNIQUE (placa),
    CONSTRAINT fk_veiculo_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente),
    -- aceita o padrão antigo (ABC1234) e o Mercosul (ABC1D23)
    CONSTRAINT ck_veiculo_placa CHECK (placa ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
    CONSTRAINT ck_veiculo_ano   CHECK (ano BETWEEN 1950 AND 2100)
);

-- --------------------------------------------------------------------------
-- 3. EQUIPE
-- Correção do modelo conceitual: o diagrama trazia "CodigoEquipe" e o
-- README "NomeEquipe". Os dois atributos foram mantidos.
-- --------------------------------------------------------------------------
CREATE TABLE equipe (
    id_equipe      INT GENERATED BY DEFAULT AS IDENTITY,
    codigo_equipe  VARCHAR(10) NOT NULL,
    nome_equipe    VARCHAR(50) NOT NULL,
    CONSTRAINT pk_equipe        PRIMARY KEY (id_equipe),
    CONSTRAINT uq_equipe_codigo UNIQUE (codigo_equipe),
    CONSTRAINT uq_equipe_nome   UNIQUE (nome_equipe)
);

-- --------------------------------------------------------------------------
-- 4. MECANICO
-- Mapeamento: relacionamento 1:N (Equipe é composta por Mecânicos) -> FK.
-- Endereço decomposto, como no cliente.
-- --------------------------------------------------------------------------
CREATE TABLE mecanico (
    id_mecanico    INT GENERATED BY DEFAULT AS IDENTITY,
    id_equipe      INT          NOT NULL,
    codigo         VARCHAR(10)  NOT NULL,
    nome           VARCHAR(100) NOT NULL,
    especialidade  VARCHAR(20)  NOT NULL,
    logradouro     VARCHAR(150) NOT NULL,
    cidade         VARCHAR(60)  NOT NULL,
    uf             CHAR(2)      NOT NULL,
    cep            CHAR(8)      NOT NULL,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_mecanico        PRIMARY KEY (id_mecanico),
    CONSTRAINT uq_mecanico_codigo UNIQUE (codigo),
    CONSTRAINT fk_mecanico_equipe FOREIGN KEY (id_equipe)
        REFERENCES equipe (id_equipe),
    CONSTRAINT ck_mecanico_especialidade CHECK (
        especialidade IN ('MOTOR', 'TRANSMISSAO', 'SUSPENSAO', 'FREIOS',
                          'ELETRICA', 'AR_CONDICIONADO', 'REVISAO_GERAL')
    )
);

-- --------------------------------------------------------------------------
-- 5. SERVICO (tabela de referência de mão de obra)
-- --------------------------------------------------------------------------
CREATE TABLE servico (
    id_servico         INT GENERATED BY DEFAULT AS IDENTITY,
    descricao          VARCHAR(100)  NOT NULL,
    valor_mao_de_obra  NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_servico           PRIMARY KEY (id_servico),
    CONSTRAINT uq_servico_descricao UNIQUE (descricao),
    CONSTRAINT ck_servico_valor     CHECK (valor_mao_de_obra > 0)
);

-- --------------------------------------------------------------------------
-- 6. PECA
-- --------------------------------------------------------------------------
CREATE TABLE peca (
    id_peca         INT GENERATED BY DEFAULT AS IDENTITY,
    nome_peca       VARCHAR(100)  NOT NULL,
    valor_unitario  NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_peca       PRIMARY KEY (id_peca),
    CONSTRAINT uq_peca_nome  UNIQUE (nome_peca),
    CONSTRAINT ck_peca_valor CHECK (valor_unitario > 0)
);

-- --------------------------------------------------------------------------
-- 7. ORDEM_SERVICO
-- Mapeamento: dois relacionamentos 1:N (Veículo -> OS e Equipe -> OS).
-- Regra da narrativa: "a mesma equipe avalia e executa os serviços",
-- por isso há uma única FK de equipe na OS.
-- Correção do modelo conceitual: "ValorTotal" é um atributo DERIVADO
-- (soma de serviços + peças) e NÃO é armazenado; é calculado nas consultas.
-- --------------------------------------------------------------------------
CREATE TABLE ordem_servico (
    id_os                    INT GENERATED BY DEFAULT AS IDENTITY,
    numero_os                VARCHAR(12) NOT NULL,
    id_veiculo               INT         NOT NULL,
    id_equipe                INT         NOT NULL,
    tipo_os                  VARCHAR(10) NOT NULL,
    status_os                VARCHAR(25) NOT NULL DEFAULT 'EM_AVALIACAO',
    data_emissao             DATE        NOT NULL DEFAULT CURRENT_DATE,
    data_prevista_conclusao  DATE        NOT NULL,
    data_conclusao           DATE,
    autorizado_pelo_cliente  BOOLEAN     NOT NULL DEFAULT FALSE,
    data_autorizacao         TIMESTAMP,
    observacao               VARCHAR(255),
    CONSTRAINT pk_ordem_servico        PRIMARY KEY (id_os),
    CONSTRAINT uq_ordem_servico_numero UNIQUE (numero_os),
    CONSTRAINT fk_ordem_servico_veiculo FOREIGN KEY (id_veiculo)
        REFERENCES veiculo (id_veiculo),
    CONSTRAINT fk_ordem_servico_equipe FOREIGN KEY (id_equipe)
        REFERENCES equipe (id_equipe),
    CONSTRAINT ck_ordem_servico_numero CHECK (numero_os ~ '^OS-[0-9]{4}-[0-9]{4}$'),
    CONSTRAINT ck_ordem_servico_tipo   CHECK (tipo_os IN ('CONSERTO', 'REVISAO')),
    CONSTRAINT ck_ordem_servico_status CHECK (
        status_os IN ('EM_AVALIACAO', 'AGUARDANDO_AUTORIZACAO', 'EM_EXECUCAO',
                      'CONCLUIDA', 'CANCELADA')
    ),
    -- regra de negócio: nenhuma OS é executada sem autorização do cliente
    CONSTRAINT ck_ordem_servico_execucao_autorizada CHECK (
        status_os NOT IN ('EM_EXECUCAO', 'CONCLUIDA') OR autorizado_pelo_cliente
    ),
    -- a data de autorização existe se, e somente se, houve autorização
    CONSTRAINT ck_ordem_servico_data_autorizacao CHECK (
        autorizado_pelo_cliente = (data_autorizacao IS NOT NULL)
    ),
    -- a data de conclusão existe se, e somente se, a OS foi concluída
    CONSTRAINT ck_ordem_servico_conclusao CHECK (
        (status_os = 'CONCLUIDA') = (data_conclusao IS NOT NULL)
    ),
    CONSTRAINT ck_ordem_servico_datas CHECK (
        data_prevista_conclusao >= data_emissao AND
        (data_conclusao IS NULL OR data_conclusao >= data_emissao)
    )
);

-- --------------------------------------------------------------------------
-- 8. OS_SERVICO (N:M entre OS e serviço)
-- Mapeamento: relacionamento N:M -> tabela associativa com PK composta.
-- valor_unitario guarda o preço praticado: se a tabela de mão de obra
-- mudar, o valor das OS antigas não muda.
-- --------------------------------------------------------------------------
CREATE TABLE os_servico (
    id_os           INT           NOT NULL,
    id_servico      INT           NOT NULL,
    quantidade      INT           NOT NULL DEFAULT 1,
    valor_unitario  NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_os_servico PRIMARY KEY (id_os, id_servico),
    CONSTRAINT fk_os_servico_os FOREIGN KEY (id_os)
        REFERENCES ordem_servico (id_os) ON DELETE CASCADE,
    CONSTRAINT fk_os_servico_servico FOREIGN KEY (id_servico)
        REFERENCES servico (id_servico),
    CONSTRAINT ck_os_servico_qtd   CHECK (quantidade > 0),
    CONSTRAINT ck_os_servico_valor CHECK (valor_unitario > 0)
);

-- --------------------------------------------------------------------------
-- 9. OS_PECA (N:M entre OS e peça)
-- --------------------------------------------------------------------------
CREATE TABLE os_peca (
    id_os           INT           NOT NULL,
    id_peca         INT           NOT NULL,
    quantidade      INT           NOT NULL DEFAULT 1,
    valor_unitario  NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_os_peca PRIMARY KEY (id_os, id_peca),
    CONSTRAINT fk_os_peca_os FOREIGN KEY (id_os)
        REFERENCES ordem_servico (id_os) ON DELETE CASCADE,
    CONSTRAINT fk_os_peca_peca FOREIGN KEY (id_peca)
        REFERENCES peca (id_peca),
    CONSTRAINT ck_os_peca_qtd   CHECK (quantidade > 0),
    CONSTRAINT ck_os_peca_valor CHECK (valor_unitario > 0)
);

-- --------------------------------------------------------------------------
-- 10. ÍNDICES
-- O PostgreSQL NÃO cria índice automático em chave estrangeira.
-- Indexamos as FKs que não são a primeira coluna de uma PK.
-- --------------------------------------------------------------------------
CREATE INDEX idx_veiculo_cliente        ON veiculo       (id_cliente);
CREATE INDEX idx_mecanico_equipe        ON mecanico      (id_equipe);
CREATE INDEX idx_ordem_servico_veiculo  ON ordem_servico (id_veiculo);
CREATE INDEX idx_ordem_servico_equipe   ON ordem_servico (id_equipe);
CREATE INDEX idx_os_servico_servico     ON os_servico    (id_servico);
CREATE INDEX idx_os_peca_peca           ON os_peca       (id_peca);

-- --------------------------------------------------------------------------
-- 11. DOCUMENTAÇÃO DAS TABELAS (aparece nas propriedades do DBeaver)
-- --------------------------------------------------------------------------
COMMENT ON TABLE cliente       IS 'Clientes da oficina: pessoa física (CPF) ou jurídica (CNPJ), nunca ambos';
COMMENT ON TABLE veiculo       IS 'Veículos dos clientes; um cliente pode ter vários';
COMMENT ON TABLE equipe        IS 'Equipes de mecânicos; a mesma equipe avalia e executa a OS';
COMMENT ON TABLE mecanico      IS 'Mecânicos, cada um vinculado a uma equipe';
COMMENT ON TABLE servico       IS 'Tabela de referência de mão de obra';
COMMENT ON TABLE peca          IS 'Catálogo de peças';
COMMENT ON TABLE ordem_servico IS 'Ordens de serviço; o valor total é derivado de os_servico + os_peca';
COMMENT ON TABLE os_servico    IS 'Serviços de cada OS, com o preço praticado';
COMMENT ON TABLE os_peca       IS 'Peças de cada OS, com o preço praticado';
